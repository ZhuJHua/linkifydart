/// Refreshes the compact TLD tries from the IANA root zone list.
library;

import 'dart:convert';
import 'dart:io';

import 'package:linkifydart/src/scanner.dart' show decodeTlds;

/// The authoritative IANA list of delegated top-level domains.
const tldSource = 'https://data.iana.org/TLD/tlds-alpha-by-domain.txt';

/// Updates the TLD file, setting a nonzero exit code on any failure.
///
/// Accepts `--source URL-or-file` and `--output file` without prompting.
Future<void> main(List<String> arguments) async {
  try {
    await _update(arguments);
  } catch (error) {
    stderr.writeln('TLD update failed: ${_escapeSeparators(error.toString())}');
    exitCode = 1;
  }
}

Future<void> _update(List<String> arguments) async {
  var source = tldSource;
  var output = 'lib/src/tlds.dart';
  for (var index = 0; index < arguments.length; index += 2) {
    if (index + 1 >= arguments.length ||
        !['--source', '--output'].contains(arguments[index])) {
      throw ArgumentError(
        'Usage: dart run tool/update_tlds.dart '
        '[--source URL-or-file] [--output file]',
      );
    }
    if (arguments[index] == '--source') source = arguments[index + 1];
    if (arguments[index] == '--output') output = arguments[index + 1];
  }
  String contents;
  if (source.startsWith('https://')) {
    final client = HttpClient()
      ..connectionTimeout = const Duration(seconds: 30);
    try {
      contents = await (() async {
        final response = await (await client.getUrl(Uri.parse(source))).close();
        if (response.statusCode != HttpStatus.ok) {
          throw HttpException(
            'HTTP ${response.statusCode}',
            uri: Uri.parse(source),
          );
        }
        return response.transform(utf8.decoder).join();
      })()
          .timeout(const Duration(seconds: 60));
    } finally {
      client.close(force: true);
    }
  } else {
    contents = await File(source).readAsString();
  }
  final (tlds, utlds) = parseIana(contents);
  final encoded = encodeTlds(tlds);
  final encodedUnicode = encodeTlds(utlds);
  if (jsonEncode(decodeTlds(encoded)) != jsonEncode(tlds) ||
      jsonEncode(decodeTlds(encodedUnicode)) != jsonEncode(utlds)) {
    throw StateError('TLD encoding round trip failed');
  }
  await File(output).writeAsString(
    '/// Compact TLD tries generated by `tool/update_tlds.dart` from IANA.\n'
    'library;\n\n'
    '/// The encoded ASCII and mixed-script TLD trie.\n'
    'const encodedTlds =\n'
    '    ${_dartString(encoded)};\n\n'
    '/// The encoded Unicode TLD trie.\n'
    'const encodedUtlds =\n'
    '    ${_dartString(encodedUnicode)};\n',
  );
  stdout.writeln(
    'Wrote ${tlds.length} ASCII/mixed-script TLDs and '
    '${utlds.length} Unicode TLDs to ${_escapeSeparators(output)}',
  );
}

String _escapeSeparators(String value) => value
    .replaceAll('\u2028', r'\u2028')
    .replaceAll('\u2029', r'\u2029')
    .replaceAll('\u0085', r'\u0085');

String _dartString(String value) {
  final escaped = value
      .replaceAll(r'\', r'\\')
      .replaceAll("'", r"\'")
      .replaceAll(r'$', r'\$');
  return "'${_escapeSeparators(escaped)}'";
}

/// Parses IANA labels into sorted ASCII/mixed-script and Unicode TLD lists.
///
/// Decodes Punycode labels, placing the two mixed-script German exceptions in
/// the ASCII trie. Empty lists, malformed labels, and duplicates are rejected.
(List<String>, List<String>) parseIana(String contents) {
  const special = ['xn--vermgensberater-ctb', 'xn--vermgensberatung-pwb'];
  final tlds = <String>[];
  final utlds = <String>[];
  final names = <String>{};
  for (final line in const LineSplitter().convert(contents)) {
    final name = line.trim().toLowerCase();
    if (name.isEmpty || name.startsWith('#')) {
      continue;
    }
    if (!RegExp(r'^[a-z](?:[a-z0-9-]*[a-z0-9])?$').hasMatch(name) ||
        name.length > 63 ||
        !names.add(name)) {
      throw const FormatException('Malformed or duplicate IANA TLD label');
    }
    if (special.contains(name)) continue;
    if (name.startsWith('xn--')) {
      utlds.add(decodePunycode(name.substring(4)));
    } else {
      tlds.add(name);
    }
  }
  if (names.isEmpty) throw const FormatException('The IANA TLD list is empty');
  tlds.addAll(special.map((name) => decodePunycode(name.substring(4))));
  tlds.sort();
  utlds.sort();
  return (tlds, utlds);
}

class _Trie {
  final Map<String, _Trie> children = {};
  bool isWord = false;
}

/// Encodes sorted [words] into the compact trie consumed by [decodeTlds].
///
/// Words must not contain ASCII digits, which encode trie backtracking counts.
String encodeTlds(List<String> words) {
  final root = _Trie();
  for (final word in words) {
    var node = root;
    for (final point in word.runes) {
      node = node.children.putIfAbsent(String.fromCharCode(point), _Trie.new);
    }
    node.isWord = true;
  }
  List<Object> encode(_Trie node) {
    final result = <Object>[if (node.isWord) 0];
    for (final entry in node.children.entries) {
      result.add(entry.key);
      result.addAll(encode(entry.value));
      if (result.last is int) {
        result[result.length - 1] = (result.last as int) + 1;
      } else {
        result.add(1);
      }
    }
    return result;
  }

  return encode(root).join();
}

/// Decodes a single Punycode label as specified by RFC 3492 section 6.2.
String decodePunycode(String input) {
  const base = 36;
  var codePoint = 128;
  var insertion = 0;
  var bias = 72;
  final output = <int>[];
  final delimiter = input.lastIndexOf('-');
  var cursor = 0;
  if (delimiter >= 0) {
    output.addAll(input.substring(0, delimiter).codeUnits);
    cursor = delimiter + 1;
  }
  while (cursor < input.length) {
    final previous = insertion;
    var weight = 1;
    for (var step = base;; step += base) {
      if (cursor >= input.length) {
        throw const FormatException('Invalid Punycode');
      }
      final unit = input.codeUnitAt(cursor++);
      final digit = unit >= 48 && unit <= 57
          ? unit - 22
          : unit >= 97 && unit <= 122
              ? unit - 97
              : -1;
      if (digit < 0) throw const FormatException('Invalid Punycode digit');
      insertion += digit * weight;
      final threshold =
          step <= bias ? 1 : (step >= bias + 26 ? 26 : step - bias);
      if (digit < threshold) break;
      weight *= base - threshold;
    }
    final length = output.length + 1;
    var delta = insertion - previous;
    delta = previous == 0 ? delta ~/ 700 : delta ~/ 2;
    delta += delta ~/ length;
    var adaptation = 0;
    while (delta > 455) {
      delta ~/= 35;
      adaptation += base;
    }
    bias = adaptation + 36 * delta ~/ (delta + 38);
    codePoint += insertion ~/ length;
    if (codePoint > 0x10ffff) throw const FormatException('Invalid code point');
    insertion %= length;
    output.insert(insertion, codePoint);
    insertion++;
  }
  return String.fromCharCodes(output);
}
